
using DeveloperProjectTrackerDomain.Entities;
using Microsoft.EntityFrameworkCore;

namespace DeveloperProjectTracker.API.Data
{
    public class ApplicationDbContext : DbContext
    {
        public ApplicationDbContext(
            DbContextOptions<ApplicationDbContext> options)
            : base(options)
        {
        }

        // =========================================================
        // DB SETS
        // =========================================================

        public DbSet<User> Users => Set<User>();

        public DbSet<Project> Projects => Set<Project>();

        public DbSet<ProjectMember> ProjectMembers => Set<ProjectMember>();

        public DbSet<TaskItem> TaskItems => Set<TaskItem>();

        public DbSet<TaskAssignment> TaskAssignments => Set<TaskAssignment>();

        public DbSet<Comment> Comments => Set<Comment>();

        public DbSet<Label> Labels => Set<Label>();

        public DbSet<TaskLabel> TaskLables => Set<TaskLabel>();

        public DbSet<Milestone> Milestones => Set<Milestone>();

        public DbSet<WorkLog> Worklogs => Set<WorkLog>();

        public DbSet<Notification> Notifications => Set<Notification>();

        public DbSet<ActivityLog> ActivityLogs => Set<ActivityLog>();

        public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();

        public DbSet<Tenant> Tenants => Set<Tenant>();

        public DbSet<TenantMembership> TenantMemberships =>
            Set<TenantMembership>();

        // =========================================================
        // MODEL CONFIGURATION
        // =========================================================

        protected override void OnModelCreating(
            ModelBuilder modelBuilder)
        {
            base.OnModelCreating(modelBuilder);

            // Apply all IEntityTypeConfiguration<T> classes
            // located in the API assembly.
            modelBuilder.ApplyConfigurationsFromAssembly(
                typeof(ApplicationDbContext).Assembly);

            // =====================================================
            // TASK ASSIGNMENT CONFIGURATION
            // =====================================================

            modelBuilder.Entity<TaskAssignment>(entity =>
            {
                entity.ToTable("TaskAssignments");

                // Primary key
                entity.HasKey(x => x.Id);

                // IDs are generated by the application using Guid.NewGuid().
                entity.Property(x => x.Id)
                    .ValueGeneratedNever();

                // Assignment timestamp
                entity.Property(x => x.AssignedAt)
                    .IsRequired()
                    .HasColumnType("timestamp with time zone");

                // Task relationship:
                // One task can have multiple assignments.
                entity.HasOne(x => x.Task)
                    .WithMany(x => x.Assignments)
                    .HasForeignKey(x => x.TaskId)
                    .OnDelete(DeleteBehavior.Cascade);

                // User relationship:
                // Prevent deleting a user while assignment records
                // reference that user.
                entity.HasOne(x => x.User)
                    .WithMany()
                    .HasForeignKey(x => x.UserId)
                    .OnDelete(DeleteBehavior.Restrict);

                // Prevent assigning the same user to a task twice.
                entity.HasIndex(x => new
                {
                    x.TaskId,
                    x.UserId
                })
                    .IsUnique();
            });
        }
    }
}
